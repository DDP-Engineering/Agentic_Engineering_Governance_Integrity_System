"""
@file test_repo_evolution.py
@brief Regression tests for repository anchor and evolution records.
@details Throwaway Git repositories exercise visible-file selection, stable
         fingerprints, compact history, machine output, and advisory checks.
"""

# IMPORTS

from __future__ import annotations

import hashlib
import importlib.util
import itertools
import json
import shutil
import subprocess
from pathlib import Path

import pytest

# CONSTANTS

PAYLOAD = Path(__file__).resolve().parents[1] / "template" / ".agentic"
_COUNTER = itertools.count()
HAS_GIT = shutil.which("git") is not None
needs_git = pytest.mark.skipif(not HAS_GIT, reason="git executable not available")

# HELPERS


def write(path: Path, text: str) -> Path:
    """@brief Write one LF-normalized fixture file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def git(repo: Path, *args: str) -> str:
    """@brief Run Git with deterministic test identity and return stdout."""
    done = subprocess.run(
        ["git", "-c", "user.email=t@example.com", "-c", "user.name=T",
         "-c", "commit.gpgsign=false", *args],
        cwd=str(repo), check=True, capture_output=True, timeout=60,
    )
    return done.stdout.decode("utf-8", errors="replace").strip()


def make_repo(tmp_path: Path) -> tuple[Path, object]:
    """@brief Create an initialized AEGIS fixture on a feature branch."""
    agentic = tmp_path / ".agentic"
    shutil.copytree(PAYLOAD, agentic)
    spec = importlib.util.spec_from_file_location(
        f"aegis_evolution_{next(_COUNTER)}", agentic / "aegis.py"
    )
    aegis = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(aegis)
    aegis.main(["init"])
    write(tmp_path / "src" / "app.py", "VALUE = 1\n")
    write(tmp_path / "tests" / "test_app.py", "def test_app():\n    assert True\n")
    write(tmp_path / "README.md", "fixture\n")
    write(tmp_path / ".gitignore", "ignored/\n*.cache\n")
    git(tmp_path, "init")
    git(tmp_path, "symbolic-ref", "HEAD", "refs/heads/master")
    git(tmp_path, "add", "-A")
    git(tmp_path, "commit", "-m", "base")
    git(tmp_path, "checkout", "-b", "feature")
    task = write(
        agentic / "tasks" / "TASK-abcd.md",
        "# TASK-abcd - state fixture\n\n"
        "stage: build\ntype: feature\npath: full\nrequirements:\n"
        f"branch: feature\nbase: {git(tmp_path, 'rev-parse', 'HEAD')}\n"
        "opened: 2026-08-14\n\n## Done checklist\n\n- [ ] done\n\n"
        "## Log\n\n- 2026-08-14 build: opened\n",
    )
    assert task.is_file()
    return agentic, aegis


def load(path: Path) -> dict:
    """@brief Read one generated JSON record."""
    return json.loads(path.read_text(encoding="utf-8"))


# TESTS


@needs_git
def test_anchor_records_visible_files_metadata_and_hashes(tmp_path, capsys):
    """Anchor includes tracked/untracked files, excluding ignored and AEGIS data."""
    agentic, aegis = make_repo(tmp_path)
    write(tmp_path / "docs" / "notes.md", "untracked\n")
    write(tmp_path / "docs" / "naïve file.md", "unicode and spaces\n")
    write(tmp_path / "ignored" / "cache.txt", "ignored\n")
    write(tmp_path / "scratch.cache", "ignored\n")
    write(tmp_path / "src" / "__pycache__" / "app.cpython-312.pyc",
          "generated bytecode\n")

    assert aegis.main(["anchor", "--task", "TASK-abcd"]) == 0
    out = capsys.readouterr().out
    record = load(agentic / "tasks" / "TASK-abcd.anchor.json")

    assert "anchored" in out
    assert record["schema"] == 1
    assert record["task"] == "TASK-abcd"
    assert record["stage"] == "build"
    assert record["created_at"].endswith("Z")
    assert len(record["anchor_id"]) == 16
    assert record["files"]["src/app.py"] == {
        "kind": "file",
        "sha256": hashlib.sha256(b"VALUE = 1\n").hexdigest(),
    }
    assert record["categories"]["src/app.py"] == "source"
    assert record["categories"]["tests/test_app.py"] == "tests"
    assert record["categories"]["README.md"] == "other"
    assert "docs/notes.md" in record["files"]
    assert "docs/naïve file.md" in record["files"]
    assert not any(path.startswith(".agentic/") for path in record["files"])
    assert "ignored/cache.txt" not in record["files"]
    assert "scratch.cache" not in record["files"]
    assert "src/__pycache__/app.cpython-312.pyc" not in record["files"]


@needs_git
def test_generated_python_bytecode_does_not_change_evolution(tmp_path, capsys):
    """Creating a Python cache after anchoring produces no evolution change."""
    _agentic, aegis = make_repo(tmp_path)
    assert aegis.main(["anchor", "--task", "TASK-abcd"]) == 0
    capsys.readouterr()
    write(tmp_path / "src" / "__pycache__" / "app.cpython-312.pyc",
          "generated bytecode\n")

    assert aegis.main(["evolution", "--task", "TASK-abcd", "--json"]) == 0
    result = json.loads(capsys.readouterr().out)
    assert result["changes"] == []
    assert result["counts"]["status"]["added"] == 0


@needs_git
def test_evolution_classifies_changes_and_retains_compact_history(tmp_path,
                                                                  capsys):
    """Evolution records file-level changes and refreshes the active pair."""
    agentic, aegis = make_repo(tmp_path)
    assert aegis.main(["anchor", "--task", "TASK-abcd"]) == 0
    capsys.readouterr()
    anchor = load(agentic / "tasks" / "TASK-abcd.anchor.json")
    write(agentic / "aegis.toml", "[layout]\nsource = ['lib/']\ntests = ['spec/']\n")

    write(tmp_path / "src" / "app.py", "VALUE = 2\n")
    (tmp_path / "tests" / "test_app.py").unlink()
    write(tmp_path / "docs" / "new.md", "new\n")
    assert aegis.main(["evolution", "--task", "TASK-abcd"]) == 0
    out = capsys.readouterr().out
    history = load(agentic / "tasks" / "TASK-abcd.evolution.json")
    report = history["reports"][0]

    assert "MODIFIED [source] src/app.py" in out
    assert "REMOVED [tests] tests/test_app.py" in out
    assert "ADDED [other] docs/new.md" in out
    assert report["anchor_id"] == anchor["anchor_id"]
    assert report["anchor_created_at"] == anchor["created_at"]
    assert report["evolved_at"].endswith("Z")
    assert report["counts"]["status"] == {
        "added": 1, "modified": 1, "removed": 1, "unchanged": 5,
    }
    assert [item["path"] for item in report["changes"]] == [
        "docs/new.md", "src/app.py", "tests/test_app.py",
    ]
    assert all(item["status"] != "unchanged" for item in report["changes"])

    write(tmp_path / "src" / "app.py", "VALUE = 3\n")
    assert aegis.main(["evolution", "--task", "TASK-abcd"]) == 0
    capsys.readouterr()
    refreshed = load(agentic / "tasks" / "TASK-abcd.evolution.json")
    assert len(refreshed["reports"]) == 1
    source = next(item for item in refreshed["reports"][0]["changes"]
                  if item["path"] == "src/app.py")
    assert source["after"]["sha256"] == hashlib.sha256(b"VALUE = 3\n").hexdigest()


@needs_git
def test_new_anchor_preserves_completed_reports_and_flags_unmatched_replacement(
        tmp_path, capsys):
    """Completed pairs survive while replacing an incomplete anchor is visible."""
    agentic, aegis = make_repo(tmp_path)
    assert aegis.main(["anchor", "--task", "TASK-abcd"]) == 0
    first = load(agentic / "tasks" / "TASK-abcd.anchor.json")["anchor_id"]
    assert aegis.main(["evolution", "--task", "TASK-abcd"]) == 0
    assert aegis.main(["anchor", "--task", "TASK-abcd"]) == 0
    second = load(agentic / "tasks" / "TASK-abcd.anchor.json")["anchor_id"]
    out = capsys.readouterr().out
    assert first != second and "replaced completed anchor" in out
    assert len(load(agentic / "tasks" / "TASK-abcd.evolution.json")["reports"]) == 1

    assert aegis.main(["anchor", "--task", "TASK-abcd"]) == 0
    assert "warning: replaced unmatched anchor" in capsys.readouterr().out


@needs_git
def test_machine_output_and_repo_evolution_notes_are_advisory(tmp_path, capsys):
    """Machine envelopes are complete and missing state remains NOTE-only."""
    agentic, aegis = make_repo(tmp_path)
    assert aegis.main(["check", "--task", "TASK-abcd"]) == 0
    assert "NOTE   repo-evolution" in capsys.readouterr().out

    assert aegis.main(["anchor", "--task", "TASK-abcd", "--json"]) == 0
    anchor_out = json.loads(capsys.readouterr().out)
    assert anchor_out["schema"] == aegis.JSON_SCHEMA
    assert anchor_out["command"] == "anchor"
    assert anchor_out["task"] == "TASK-abcd"

    assert aegis.main(["check", "--task", "TASK-abcd"]) == 0
    assert "no completed evolution" in capsys.readouterr().out

    assert aegis.main(["evolution", "--task", "TASK-abcd", "--json"]) == 0
    evolution_out = json.loads(capsys.readouterr().out)
    assert evolution_out["command"] == "evolution"
    assert evolution_out["counts"]["status"]["modified"] == 0
    assert evolution_out["changes"] == []

    assert aegis.main(["check", "--task", "TASK-abcd"]) == 0
    assert "repo-evolution" not in capsys.readouterr().out

    evolution = agentic / "tasks" / "TASK-abcd.evolution.json"
    evolution.write_text("not json\n", encoding="utf-8")
    assert aegis.main(["check", "--task", "TASK-abcd", "--json"]) == 0
    out = json.loads(capsys.readouterr().out)
    findings = [item for item in out["findings"]
                if item["check"] == "repo-evolution"]
    assert len(findings) == 1 and findings[0]["level"] == "WARN"
    assert "not valid JSON" in findings[0]["message"]


@needs_git
def test_mismatched_anchor_warns_but_ordinary_check_remains_successful(
        tmp_path, capsys):
    """A state file for another task is malformed advisory evidence."""
    agentic, aegis = make_repo(tmp_path)
    assert aegis.main(["anchor", "--task", "TASK-abcd"]) == 0
    capsys.readouterr()
    anchor_file = agentic / "tasks" / "TASK-abcd.anchor.json"
    anchor = load(anchor_file)
    anchor["task"] = "TASK-dead"
    anchor_file.write_text(json.dumps(anchor), encoding="utf-8", newline="\n")

    assert aegis.main(["check", "--task", "TASK-abcd", "--json"]) == 0
    out = json.loads(capsys.readouterr().out)
    findings = [item for item in out["findings"]
                if item["check"] == "repo-evolution"]
    assert len(findings) == 1
    assert findings[0]["level"] == "WARN"
    assert "belongs to task" in findings[0]["message"]


@needs_git
def test_anchor_fails_cleanly_without_git_and_writes_no_partial_record(
        tmp_path, monkeypatch, capsys):
    """A missing Git executable leaves no misleading partial anchor."""
    agentic, aegis = make_repo(tmp_path)
    monkeypatch.setattr(aegis, "run_git", lambda *_args: None)
    assert aegis.main(["anchor", "--task", "TASK-abcd"]) == 1
    assert "git executable not found" in capsys.readouterr().err
    assert not (agentic / "tasks" / "TASK-abcd.anchor.json").exists()


@needs_git
def test_failed_anchor_replace_preserves_previous_record_and_cleans_temp(
        tmp_path, monkeypatch, capsys):
    """An output failure cannot truncate the last complete anchor."""
    agentic, aegis = make_repo(tmp_path)
    assert aegis.main(["anchor", "--task", "TASK-abcd"]) == 0
    capsys.readouterr()
    anchor_file = agentic / "tasks" / "TASK-abcd.anchor.json"
    before = anchor_file.read_bytes()

    def fail_replace(_source, _target):
        raise OSError("replace blocked")

    monkeypatch.setattr(aegis.os, "replace", fail_replace)
    assert aegis.main(["anchor", "--task", "TASK-abcd"]) == 1
    assert "cannot write" in capsys.readouterr().err
    assert anchor_file.read_bytes() == before
    assert not list(anchor_file.parent.glob(f".{anchor_file.name}.*.tmp"))


@needs_git
def test_symlink_fingerprint_does_not_walk_external_content(tmp_path):
    """A symlink uses link identity without reading its external target."""
    _agentic, aegis = make_repo(tmp_path)
    external = write(tmp_path.parent / f"outside-{tmp_path.name}.txt", "secret\n")
    link = tmp_path / "tests" / "external-link"
    try:
        link.symlink_to(external)
    except OSError:
        pytest.skip("symlink creation is unavailable")
    value = aegis.fingerprint(link, "tests/external-link")
    assert value["kind"] == "symlink"
    assert value["sha256"] == hashlib.sha256(
        aegis.os.fsencode(aegis.os.readlink(link))
    ).hexdigest()
    assert value["sha256"] != hashlib.sha256(b"secret\n").hexdigest()


@needs_git
def test_submodule_fingerprint_uses_checked_out_commit(tmp_path, monkeypatch):
    """A submodule directory is represented only by its checked-out commit."""
    _agentic, aegis = make_repo(tmp_path)
    submodule = tmp_path / "vendor"
    submodule.mkdir()
    monkeypatch.setattr(
        aegis, "run_git",
        lambda *args: (0, "a" * 40) if args == ("-C", "vendor", "rev-parse", "HEAD")
        else None,
    )
    assert aegis.fingerprint(submodule, "vendor") == {
        "kind": "submodule", "commit": "a" * 40,
    }
